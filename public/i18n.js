function saved(key) {
  try { return localStorage.getItem('kwhtracker.' + key) ?? localStorage.getItem('wattiz.' + key); } catch { return null; }
}

function remember(key, value) {
  try { localStorage.setItem('kwhtracker.' + key, value); } catch { /* Preferences still work for this page. */ }
}

export let language = saved('language') === 'en' ? 'en' : 'tr';
export const locale = () => language === 'en' ? 'en-GB' : 'tr-TR';
export const translate = (value, lang) => lang === 'en' && Object.hasOwn(english, value) ? english[value] : value;
export const t = value => translate(value, language);
export const dateFormat = options => new Intl.DateTimeFormat(locale(), { timeZone: 'Europe/Istanbul', ...options });
export function bucketLabel(bucket, period) {
  if (period === 'week') return dateFormat({ weekday: 'short' }).format(bucket.time);
  if (period === 'year' || (period === 'all' && !/^\d{4}$/.test(bucket.label))) {
    return dateFormat({ month: 'short' }).format(bucket.time);
  }
  return bucket.label;
}

export function translateIssue(message, lang = language) {
  if (!message) return '';
  const [address, detail] = message.split(' • ', 2);
  const detailCopy = value => {
    const match = /^(.*?)( \(HTTP \d+\)\.)$/.exec(value);
    return match ? translate(match[1], lang) + match[2] : translate(value, lang);
  };
  return detail ? address + ' • ' + detailCopy(detail) : detailCopy(address);
}

export function setupPreferences(onLanguage) {
  const staticCopy = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const phrase = node.textContent.trim();
    if (Object.hasOwn(english, phrase)) staticCopy.push(() => { node.textContent = t(phrase); });
  }
  for (const node of document.querySelectorAll('[aria-label], [placeholder]')) {
    for (const name of ['aria-label', 'placeholder']) {
      const phrase = node.getAttribute(name);
      if (phrase) staticCopy.push(() => node.setAttribute(name, t(phrase)));
    }
  }
  const languageSelect = document.getElementById('language');
  const themeSelect = document.getElementById('theme');
  function updateLanguage() {
    document.documentElement.lang = language;
    languageSelect.value = language;
    staticCopy.forEach(update => update());
    onLanguage();
  }
  languageSelect.addEventListener('change', () => {
    language = languageSelect.value;
    remember('language', language);
    updateLanguage();
  });
  const theme = saved('theme');
  const systemTheme = matchMedia('(prefers-color-scheme: dark)');
  if (themeSelect) themeSelect.value = theme === 'light' || theme === 'dark' ? theme : 'system';
  function updateTheme() {
    const selected = themeSelect?.value ?? theme;
    const active = selected === 'light' || selected === 'dark' ? selected : systemTheme.matches ? 'dark' : 'light';
    document.documentElement.dataset.theme = active;
    document.querySelector('[name=theme-color]').content = active === 'dark' ? '#17241f' : '#132923';
  }
  themeSelect?.addEventListener('change', () => {
    remember('theme', themeSelect.value);
    updateTheme();
  });
  systemTheme.addEventListener('change', updateTheme);
  updateTheme();
  updateLanguage();
}
